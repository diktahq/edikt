// Negative/control: a sidecar with no yaml-language-server hint at all must
// not gain one — this migration edits an existing stale hint, it does not
// invent a new comment where none existed.
func TestConvertFileToV2_NoHintNoInsertion(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "ADR-200-y.edikt.yaml")
	raw := `schema_version: 1
topic: hooks
path: docs/architecture/decisions/ADR-200-y.md
signals:
  - hook
directives:
  - text: "Hooks must emit JSON."
    source_excerpt:
      line_start: 1
      line_end: 1
      quote: "Hooks must emit JSON."
`
	if err := os.WriteFile(path, []byte(raw), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}

	changed, err := ConvertFileToV2(path)
	if err != nil {
		t.Fatalf("ConvertFileToV2: %v", err)
	}
	if !changed {
		t.Fatal("expected changed=true (schema_version + anchor still convert)")
	}

	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read result: %v", err)
	}
	if strings.Contains(string(out), "yaml-language-server") {
		t.Fatalf("a schema hint appeared where none existed before:\n%s", out)
	}
}

// Control: a v2 sidecar whose hint already points at v2 must not be touched
// or reported changed by the hint check — idempotency holds independent of
// the source_excerpts/schema_version rungs, which already cover this file.
// Uses the real header shape (block + blank line), matching what an
// already-migrated real sidecar actually looks like on disk.
func TestConvertFileToV2_AlreadyV2HintUntouched(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "ADR-300-z.edikt.yaml")
	raw := strings.Replace(realSidecarHeader, "%s", "v2", 1) + `
schema_version: 2
topic: hooks
path: docs/architecture/decisions/ADR-300-z.md
signals:
  - hook
directives:
  - text: "Hooks must emit JSON."
    source_excerpts:
      - line_start: 1
        line_end: 1
        quote: "Hooks must emit JSON."
`
	if err := os.WriteFile(path, []byte(raw), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}

	changed, err := ConvertFileToV2(path)
	if err != nil {
		t.Fatalf("ConvertFileToV2: %v", err)
	}
	if changed {
		t.Fatal("expected changed=false — already v2 in both shape and hint")
	}
}

// Asserts the exact first line of the rewritten file, rather than only
// substring presence/absence — a stricter check than the tests above, kept
// deliberately separate as this defect class's own regression guard.
func TestConvertFileToV2_RealHeaderShape_ExactBytes(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "ADR-400-w.edikt.yaml")
	header := strings.Replace(realSidecarHeader, "%s", "v1", 1)
	raw := header + `
schema_version: 1
topic: hooks
path: docs/architecture/decisions/ADR-400-w.md
signals:
  - hook
directives:
  - text: "Hooks must emit JSON."
    source_excerpt:
      line_start: 1
      line_end: 1
      quote: "Hooks must emit JSON."
`
	if err := os.WriteFile(path, []byte(raw), 0o644); err != nil {
		t.Fatalf("write fixture: %v", err)
	}

	if _, err := ConvertFileToV2(path); err != nil {
		t.Fatalf("ConvertFileToV2: %v", err)
	}

	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read result: %v", err)
	}
	firstLine := strings.SplitN(string(out), "\n", 2)[0]
	want := "# yaml-language-server: $schema=../../../templates/schemas/gov-sidecar.v2.schema.json"
	if firstLine != want {
		t.Fatalf("first line of the rewritten file:\n  got:  %q\n  want: %q", firstLine, want)
	}
}
