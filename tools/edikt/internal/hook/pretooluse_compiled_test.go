package hook

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/diktahq/edikt/tools/edikt/internal/hook/adapter"
)

// A compile-generated governance file is managed WHOLE (D81 b). bok round 2
// edited a compiled topic file's heading and was allowed, while an edit
// inside the same file's directives region was denied — yet both are lost on
// the next compile, and until then the tree carries a rule no sidecar states.
// These tests build the payload and FIRE the hook; they do not read a
// matcher list.

func plantCompiledSurfaces(t *testing.T) string {
	t.Helper()
	root := plantManagedProject(t)
	files := map[string]string{
		filepath.Join(".claude", "rules", "governance.md"):              "# Governance\n\n## Topics\n\n- hooks\n",
		filepath.Join(".claude", "rules", "governance", "hooks.md"):     "# Hooks\n\n# Migrations\n\n- a directive\n",
		filepath.Join(".claude", "skills", "edikt-compile", "SKILL.md"): "# edikt-compile\n\nbody\n",
	}
	for rel, body := range files {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func editOf(path, oldStr, newStr string) *Invocation {
	return &Invocation{Name: "pre-tool-use", Payload: adapter.Payload{
		ToolName: "Edit", FilePath: path, OldString: oldStr, NewString: newStr,
	}}
}

func TestPreToolUse_CompiledFileIsManagedWhole(t *testing.T) {
	plantCompiledSurfaces(t)
	cases := []struct{ name, path, old string }{
		{"a topic file's heading — the edit bok was allowed to make",
			filepath.Join(".claude", "rules", "governance", "hooks.md"), "# Migrations"},
		{"a topic file's directive text",
			filepath.Join(".claude", "rules", "governance", "hooks.md"), "- a directive"},
		{"the ambient core",
			filepath.Join(".claude", "rules", "governance.md"), "## Topics"},
		{"a rendered skill package",
			filepath.Join(".claude", "skills", "edikt-compile", "SKILL.md"), "body"},
	}
	for _, c := range cases {
		res := preToolUse(editOf(c.path, c.old, "edited by hand"))
		if res.Response.Decision != adapter.DecisionDeny {
			t.Errorf("%s: must be denied, got %+v", c.name, res.Response)
			continue
		}
		// Either wording is the same claim: this file is compile output and
		// an edit to it is lost. A rendered skill keeps the by-basename
		// message the hook corpus pins byte-for-byte; the rest get the
		// directory rule's. What must never happen is an allow.
		if !strings.Contains(res.Response.Reason, "managed as a whole") &&
			!strings.Contains(res.Response.Reason, "is generated by `gov compile`") {
			t.Errorf("%s: the denial must say the file is compile output, got %q", c.name, res.Response.Reason)
		}
	}
}

// The other half of the ruling: INV-005's region hash is unchanged for
// user-owned files, so an edit to CLAUDE.md OUTSIDE its managed region is
// still allowed. Denying it would take a file the user owns away from them.
func TestPreToolUse_UserFileOutsideTheRegionIsStillAllowed(t *testing.T) {
	plantCompiledSurfaces(t)
	res := preToolUse(editOf("CLAUDE.md", "tail", "tail, edited by the user"))
	if res.Response.Decision == adapter.DecisionDeny {
		t.Fatalf("an edit outside CLAUDE.md's managed region must be allowed; got %+v", res.Response)
	}
}

// A file of the same name that is NOT compile output belongs to the user.
func TestPreToolUse_SameNameOutsideTheCompiledTreeIsAllowed(t *testing.T) {
	root := plantCompiledSurfaces(t)
	p := filepath.Join(root, "docs", "governance.md")
	if err := os.WriteFile(p, []byte("# My own notes\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	res := preToolUse(editOf(filepath.Join("docs", "governance.md"), "notes", "notes, edited"))
	if res.Response.Decision == adapter.DecisionDeny {
		t.Fatalf("a user's own governance.md outside the compiled tree must be allowed; got %+v", res.Response)
	}
}

// The compile itself still writes these files: B2's in-progress switch is
// checked before the scope rules, and this stays true with the new denial.
func TestPreToolUse_CompileInProgressStillWritesCompiledFiles(t *testing.T) {
	plantCompiledSurfaces(t)
	t.Setenv("EDIKT_COMPILE_IN_PROGRESS", "1")
	res := preToolUse(editOf(filepath.Join(".claude", "rules", "governance", "hooks.md"), "- a directive", "- another"))
	if res.Response.Decision == adapter.DecisionDeny {
		t.Fatalf("gov compile must be able to write its own output; got %+v", res.Response)
	}
}
